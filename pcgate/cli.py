def _available_checkpoints(cfg, setting):
    root = Path(cfg["paths"]["results"]) / setting
    return sorted({p.parent.parent.name for p in root.glob("*/seed*/model.pt")}) if root.is_dir() else []


def _load_model(cfg, setting, mname, seed, device):
    ckpt = Path(cfg["paths"]["results"]) / setting / mname / f"seed{seed}" / "model.pt"
    if not ckpt.exists():
        have = _available_checkpoints(cfg, setting)
        raise SystemExit(
            f"no trained checkpoint for model '{mname}' seed {seed} in setting '{setting}'.\n"
            f"  looked for: {ckpt}\n"
            f"  models with a checkpoint here: {have or 'none'}\n"
            f"  -> train it first (`pcgate run --config <cfg> --only {mname}`), pick another model "
            f"with --model, or point the config at the results directory that holds the checkpoints. "
            f"Note that `run` saves model.pt next to each run's metrics, and the Colab results zip "
            f"excludes *.pt, so checkpoints do not travel with downloaded results.")
    split, graph = _load(cfg, setting, device)
    in_dim = next(iter(graph.x.values())).size(1)
    model = LinkModel(mname, graph.metadata(), in_dim, run_cfg(cfg, mname)["model"], graph.num_nodes).to(device)
    sd = torch.load(ckpt, map_location=device)
    model.load_state_dict(sd)
    model.eval()
    return split, graph, model


def _popularity_for(split, graph):
    deg = torch.zeros(graph.num_nodes["drug"], dtype=torch.long)
    for (st, _, dt), e in graph.edge_index.items():
        if dt == "drug":
            deg += torch.bincount(e[1].cpu(), minlength=graph.num_nodes["drug"])
    return Popularity(graph.num_nodes["drug"], split.train, deg)


def cmd_candidates(cfg, args):
    c = cfg.get("candidates", {})
    if args.model:
        c = dict(c, model=args.model)
    dev = _device(cfg)
    setting, mname = c.get("setting", "random"), c.get("model", "gated")
    if mname == "popularity":
        split, graph = _load(cfg, setting, dev)
        pop = _popularity_for(split, graph)
        model = None
    else:
        split, graph, model = _load_model(cfg, setting, mname, c.get("seed", 0), dev)
    known = {(int(a), int(b)) for a, b in split.all_known}
    n_drugs = graph.num_nodes["drug"]
    diseases = np.unique(split.all_known[:, 1]) if c.get("diseases", "with_indication") == "with_indication" \
        else np.arange(graph.num_nodes["disease"])
    top_k = c.get("top_k_per_disease", 10)
    with torch.no_grad():
        h, ctx = model.encode(graph.x, graph.edge_index) if model is not None else (None, None)
        rows = []
        drugs = torch.arange(n_drugs, device=dev)
        for s in diseases:
            ss = torch.full((n_drugs,), int(s), device=dev)
            if model is None:
                p, alpha = pop.score_pairs(drugs.cpu(), ss.cpu()).numpy(), None
            else:
                logit, alpha = model.score(h, ctx, drugs, ss, return_alpha=True)
                p = torch.sigmoid(logit).cpu().numpy()
            order = np.argsort(-p)
            r = 0
            for d in order:
                if (int(d), int(s)) in known:
                    continue
                r += 1
                row = {"disease": graph.node_names["disease"][s], "disease_id": graph.node_ids["disease"][s],
                       "rank": r, "drug": graph.node_names["drug"][d], "drug_id": graph.node_ids["drug"][d],
                       "score": float(p[d])}
                if alpha is not None:
                    for v in ("drug", "disease"):
                        w = alpha[v][d].cpu().numpy()
                        j = int(np.argmax(w))
                        row[f"top_{v}_relation"] = model.summ.rels[v][j][1]
                        row[f"top_{v}_weight"] = float(w[j])
                rows.append(row)
                if r >= top_k:
                    break
    df = pd.DataFrame(rows).sort_values(["score", "disease", "rank"], ascending=[False, True, True])
    df.insert(0, "model", mname)
    df.insert(1, "setting", setting)
    out = Path(cfg["paths"]["results"]) / f"candidates_{mname}_{setting}.csv"
    df.to_csv(out, index=False)
    print(f"wrote {out}  ({len(df)} rows; computational hypotheses only - not validated)")
    print(df.head(15).to_string(index=False))


def cmd_explain(cfg, args):
    from .explain import PathExplainer
    e = cfg.get("explain", {})
    dev = _device(cfg)
    setting = e.get("setting", "disease")
    mname = args.model or e.get("model", "gated")
    split, graph, model = _load_model(cfg, setting, mname, e.get("seed", 0), dev)
    set_seed(e.get("seed", 0))
    scorer = make_nn_scorer(model, graph, dev)
    te = split.test
    pos_scores = scorer(te[:, 0], te[:, 1])
    # 1) strongest recovered test indications
    strong = [tuple(te[i]) for i in np.argsort(-pos_scores)[:4]]
    # 2) high-scoring unlabeled pairs (label "errors" / candidate hypotheses)
    ap = split.test_pool.ap_pairs[split.test_pool.ap_labels == 0]
    ap_sc = scorer(ap[:, 0], ap[:, 1])
    wrong = [tuple(ap[i]) for i in np.argsort(-ap_sc)[:3]]
    # 3) limited-evidence test indications: lowest combined degree
    deg_d = np.zeros(graph.num_nodes["drug"])
    deg_s = np.zeros(graph.num_nodes["disease"])
    for (st, _, dt), ei in graph.edge_index.items():
        if dt == "drug":
            deg_d += np.bincount(ei[1].cpu().numpy(), minlength=len(deg_d))
        if dt == "disease":
            deg_s += np.bincount(ei[1].cpu().numpy(), minlength=len(deg_s))
    limited = [tuple(te[i]) for i in np.argsort(deg_d[te[:, 0]] + deg_s[te[:, 1]])[:3]]
    cases = [("strong_test_positive", p) for p in strong] + [("high_scoring_unlabeled", p) for p in wrong] + \
        [("limited_evidence_test_positive", p) for p in limited]
    cases = cases[: e.get("n_cases", 10)]
    ex = PathExplainer(model, graph, dev, max_paths=e.get("max_paths", 5), n_random=e.get("n_random", 20))
    out = []
    for kind, (d, s) in cases:
        r = ex.explain(int(d), int(s))
        r["case_type"] = kind
        out.append(r)
        print(f"[{kind}] {r['drug_name']} -> {r['disease_name']}  p={r['score']:.3f}  paths={r['n_paths_found']}")
        for p in r["paths"]:
            print(f"     delta={p['delta']:+.4f}  random={p['random_delta_mean']:+.4f}±{p['random_delta_std']:.4f}  "
                  f"p={p['empirical_p']:.2f}  {p['path']}")
    path = Path(cfg["paths"]["results"]) / "explanations.json"
    write_json(out, path)
    print(f"wrote {path}")


