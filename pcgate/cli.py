def _device(cfg):
    d = cfg.get("device", "auto")
    if d == "auto":
        d = "cuda" if torch.cuda.is_available() else "cpu"
    return torch.device(d)


def _split_dir(cfg, setting):
    """Split directory. The candidate-pool policy is part of the name, so the all-drug and
    eligible-drug protocols can coexist and stay independently reproducible."""
    pol = cfg["data"].get("eligible_drugs", "all")
    suffix = "" if pol == "all" else f"_{pol}"
    return (Path(cfg["paths"]["processed"]) / "splits"
            / f"{setting}_s{cfg['data'].get('split_seed', 0)}{suffix}")


def _load(cfg, setting, device):
    split = Split.load(_split_dir(cfg, setting))
    graph = build_graph(cfg["paths"]["processed"], split, cfg["data"]).to(device)
    return split, graph


