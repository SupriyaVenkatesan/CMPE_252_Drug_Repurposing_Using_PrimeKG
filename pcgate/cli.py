def cmd_prepare(cfg, args):
    from .utils import sha256_file
    dcfg = cfg["data"]
    proc = Path(cfg["paths"]["processed"])
    # Audit/clean/map is deterministic and slow; reuse it when the pinned raw file is unchanged.
    done = proc / "audit.json"
    if done.exists() and not args.force and read_json(done)["raw_sha256"] == sha256_file(cfg["paths"]["raw_csv"]):
        audit = read_json(done)
        print(f"reusing preprocessed data in {proc} (raw SHA-256 unchanged; --force to redo)")
    else:
        audit = preprocess(cfg["paths"]["raw_csv"], proc, dcfg)
    print(f"audit: {audit['raw_rows']} raw rows -> {audit['unique_canonical_edges']} canonical edges, "
          f"{audit['invalid_rows']} invalid rows logged, {audit['unique_indication_pairs']} indication pairs")
    ind = pd.read_csv(proc / "indications.csv").to_numpy(np.int64)
    nodes = pd.read_csv(proc / "nodes.csv", usecols=["type"])
    n_drugs = int((nodes["type"] == "drug").sum())
    policy = dcfg.get("eligible_drugs", "all")
    eligible = np.unique(ind[:, 0]) if policy == "with_indication" else None
    print(f"candidate-drug policy: {policy} "
          f"({len(eligible) if eligible is not None else n_drugs} of {n_drugs} drug nodes)")
    all_ok = True
    for setting in cfg["experiments"].get("all_settings", SETTINGS):
        sp = make_split(ind, n_drugs, setting, dcfg.get("split_seed", 0),
                        tuple(dcfg.get("split_fractions", (0.7, 0.15, 0.15))),
                        dcfg.get("unlabeled_ratio", 10), eligible)
        sp.save(_split_dir(cfg, setting))
        man = read_json(_split_dir(cfg, setting) / "manifest.json")
        man["eligible_drugs_policy"] = policy
        man["n_drug_nodes"] = n_drugs
        write_json(man, _split_dir(cfg, setting) / "manifest.json")
        sp = Split.load(_split_dir(cfg, setting))
        g = build_graph(proc, sp, dcfg)
        chk = run_checks(proc, sp, g, dcfg)
        chk["graph"] = {"num_nodes": g.num_nodes, "num_edges": {"|".join(k): int(v.size(1)) for k, v in g.edge_index.items()},
                        "feature_dim": len(g.feature_names)}
        write_json(chk, _split_dir(cfg, setting) / "integrity_checks.json")
        man = read_json(_split_dir(cfg, setting) / "manifest.json")
        print(f"[{setting}] train/val/test = {man['n_train']}/{man['n_val']}/{man['n_test']}  "
              f"test queries={man['test_queries']}  checks passed={chk['all_passed']}")
        all_ok &= chk["all_passed"]
    if not all_ok:
        print("INTEGRITY CHECKS FAILED - see integrity_checks.json; experiments must not run.")
        sys.exit(1)


class _Counting:
    def __init__(self, f):
        self.f, self.n = f, 0

    def __call__(self, d, s):
        self.n += len(d)
        return self.f(d, s)


def _evaluate_test(scorer, split):
    cs = _Counting(scorer)
    t0 = time.time()
    m = evaluate_pool(cs, split.test_pool)
    dt = time.time() - t0
    m["eval_time_s"] = dt
    m["throughput_pairs_per_s"] = cs.n / max(dt, 1e-9)
    return m


def run_one(cfg, setting, model_name, seed, split, graph, device, out_dir: Path, log=print):
    out_dir.mkdir(parents=True, exist_ok=True)
    if model_name == "popularity":
        pop = _popularity_for(split, graph)
        m = _evaluate_test(make_pop_scorer(pop), split)
        info = {"train_time_s": 0.0, "params": {"total": 0}, "peak_memory_mb": float("nan")}
    else:
        model, info = train_model(model_name, graph, split, cfg, seed, device, log=log)
        torch.save(model.state_dict(), out_dir / "model.pt")
        pd.DataFrame(info["history"]).to_csv(out_dir / "history.csv", index=False)
        m = _evaluate_test(make_nn_scorer(model, graph, device), split)
    m.update({"setting": setting, "model": model_name, "seed": seed, "train": info})
    write_json(m, out_dir / "metrics.json")
    return m


def cmd_run(cfg, args):
    dev = _device(cfg)
    ex = cfg["experiments"]
    res_dir = Path(cfg["paths"]["results"])
    plan = []
    for setting in ex["settings"]:
        for mname in ex["models"]:
            seeds = [0] if mname == "popularity" else ex["seeds"]
            plan += [(setting, mname, s) for s in seeds]
    for setting in ex.get("control_settings", []):
        for mname in ex.get("control_models", []):
            plan += [(setting, mname, s) for s in ex["seeds"]]
    if args.only:
        plan = [p for p in plan if p[1] in args.only]
    log = get_logger(res_dir / "run.log").info
    log(f"run start: device={dev} plan={len(dict.fromkeys(plan))} runs config={args.config}")
    cache = {}
    for setting, mname, seed in dict.fromkeys(plan):
        out = res_dir / setting / mname / f"seed{seed}"
        if (out / "metrics.json").exists() and not args.force:
            log(f"skip {setting}/{mname}/seed{seed} (exists)")
            continue
        if setting not in cache:
            cache.clear()
            cache[setting] = _load(cfg, setting, dev)
            # Re-run the checks against THIS config's graph and feature policy: the file written
            # by `prepare` describes the policy in force then, which an ablation may have changed.
            split_, graph_ = cache[setting]
            chk = run_checks(cfg["paths"]["processed"], split_, graph_, cfg["data"])
            chk["feature_dim"] = len(graph_.feature_names)
            chk["indication_derived_features"] = [f for f in graph_.feature_names if "indication" in f]
            write_json(chk, res_dir / setting / "integrity_checks.json")
            if not chk["all_passed"]:
                raise SystemExit(f"integrity checks failed for {setting}: "
                                 f"{[k for k, v in chk.items() if k[0].isdigit() and v is False]}")
            log(f"[{setting}] integrity checks passed; {chk['feature_dim']} features, "
                f"{len(chk['indication_derived_features'])} indication-derived")
        split, graph = cache[setting]
        log(f"=== {setting} / {mname} / seed {seed} ===")
        m = run_one(cfg, setting, mname, seed, split, graph, dev, out, log=log)
        log(f"    test AP={m['ap']:.4f}  R@10={m['recall@10']:.4f}  AUROC={m['auroc']:.4f}  "
              f"NDCG@10={m['ndcg@10']:.4f}  time={m['train']['train_time_s']:.1f}s")


